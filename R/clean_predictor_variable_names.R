clean_predictor_variable_names <- function(modeling_vars_final){
  
  clean_predictor_variable_names = modeling_vars_final %>%
    unlist() %>%
    as.data.frame() %>%
    remove_rownames() %>%
    rename(variable = 1) %>%
    distinct() %>%
    mutate(
           
           variable_clean = case_when(variable == "surface_area" ~ "surface~area",
                                      variable == "mean_depth" ~ "mean~depth",
                                      variable == "site_depth" ~ "site~depth",
                                      variable == "littoral_fraction" ~ "littoral~fraction",
                                      variable == "buoyf" ~ "buoyancy~frequency",
                                      variable == "chla_lab_shallow" ~ "chl-a~extracted~(shallow)",
                                      variable == "tp_shallow" ~ "TP~(shallow)",
                                      variable == "tn_shallow" ~ "TN~(shallow)",
                                      variable == "op_shallow" ~ "OP~(shallow)",
                                      variable == "toc_shallow" ~ "TOC~(shallow)",
                                      variable == "turbidity_shallow" ~ "turbidity~(shallow)",
                                      variable == "chla_sonde_shallow" ~ "chl-a~sonde~(shallow)",
                                      variable == "nla17_sed_c" ~ "sediment~C",
                                      variable == "temp_deep" ~ "water~temperature~(deep)",
                                      variable == "temp_shallow" ~ "water~temperature~(shallow)",
                                      variable == "e_i" ~ "E:I",
                                      variable == "residence_time" ~ "residence~time",
                                      variable == "rda" ~ "relative~drainage~area",
                                      variable == "nh4_shallow" ~ "NH[4]~(shallow)",
                                      variable == "so4_shallow" ~ "SO[4]~(shallow)",
                                      variable == "do_deep" ~ "DO~(deep)",
                                      variable == "year_completed" ~ "year~completed",
                                      variable == "ag_eco9_nm" ~ "eco-region",
                                      variable == "wsareasqkm" ~ "watershed~area",
                                      variable == "do_shallow" ~ "DO~(shallow)",
                                      variable == "chl_predicted_sample_month_visit1" ~ "chl-a~remotely~sensed",
                                      variable == "doc_predicted_sample_month_visit1" ~ "DOC~remotely~sensed",
                                      variable == "precip8110cat" ~ "precipitation~(30-year~mean)",
                                      variable == "runoffcat" ~ "runoff",
                                      variable == "tmax8110cat" ~ "maximum~air~temperature~(30-year~mean)",
                                      variable == "kffactcat" ~ "soil~erodibility~factor",
                                      variable == "omcat" ~ "soil~organic~matter",
                                      variable == "scat" ~ "lithological~sulfur",
                                      variable == "pctcrop2019cat" ~ "row~crop~percentage",
                                      variable == "nitrogencat" ~ "lithological~nitrogen",
                                      variable == "agkffactcat" ~ "agriculture~soil~erodibility~factor",
                                      variable == "elevcat" ~ "elevation",
                                      variable == "precipitation_chamber" ~ "precipitation~(chamber~deployment)",
                                      variable == "wind_speed_chamber" ~ "wind~speed~(chamber~deployment)",
                                      variable == "delta_bp_diff" ~ "pressure~change~(chamber~deployment)",
                                      variable == "shortwave_radiation_sum_mj_m2" ~ "shortwave~radiation",
                                      variable == "precipitation_trap" ~ "precipitation~(trap~deployment)",
                                      variable == "wind_speed_trap" ~ "wind~speed~(trap~deployment)",
                                      variable == "delta_bp_ebu" ~ "pressure~change~(trap~deployment)"
           ),
           
           superscript = case_when(variable %in% c("shortwave_radiation_sum_mj_m2") ~ "^a",
                                   variable %in% c("precipitation_chamber",
                                                   "wind_speed_chamber",
                                                   "delta_bp_diff") ~ "^b",
                                   variable %in% c("precipitation_trap",
                                                   "wind_speed_trap",
                                                   "delta_bp_ebu") ~ "^c",
                                   TRUE ~ ""),
           
           units = case_when(variable == "surface_area" ~ "km^2",
                             variable == "mean_depth" ~ "m",
                             variable == "site_depth" ~ "m",
                             variable == "littoral_fraction" ~ "'%'",
                             variable == "buoyf" ~ "s^-2",
                             variable == "chla_lab_shallow" ~ "μg~L^-1",
                             variable == "tp_shallow" ~ "μg~P~L^-1",
                             variable == "tn_shallow" ~ "μg~N~L^-1",
                             variable == "op_shallow" ~ "μg~P~L^-1",
                             variable == "toc_shallow" ~ "mg~C~L^-1",
                             variable == "turbidity_shallow" ~ "NTU",
                             variable == "chla_sonde_shallow" ~ "μg~L^-1",
                             variable == "nla17_sed_c" ~ "'%'~dry~weight",
                             variable == "temp_deep" ~ "°C",
                             variable == "temp_shallow" ~ "°C",
                             variable == "e_i" ~ "unitless",
                             variable == "residence_time" ~ "y",
                             variable == "rda" ~ "unitless",
                             variable == "nh4_shallow" ~ "μg~N~L^-1",
                             variable == "so4_shallow" ~ "mg~L^-1",
                             variable == "do_deep" ~ "mg~L^-1",
                             variable == "year_completed" ~ "y",
                             variable == "ag_eco9_nm" ~ "unitless",
                             variable == "wsareasqkm" ~ "km^2",
                             variable == "do_shallow" ~ "mg~L^-1",
                             variable == "chl_predicted_sample_month_visit1" ~ "μg~L^-1",
                             variable == "doc_predicted_sample_month_visit1" ~ "mg~C~L^-1",
                             variable == "precip8110cat" ~ "mm",
                             variable == "runoffcat" ~ "mm",
                             variable == "tmax8110cat" ~ "°C",
                             variable == "kffactcat" ~ "unitless",
                             variable == "omcat" ~ "'%'",
                             variable == "scat" ~ "'%'",
                             variable == "pctcrop2019cat" ~ "'%'",
                             variable == "nitrogencat" ~ "'%'",
                             variable == "agkffactcat" ~ "unitless",
                             variable == "elevcat" ~ "m",
                             variable == "precipitation_chamber" ~ "m",
                             variable == "wind_speed_chamber" ~ "m~s^-1",
                             variable == "delta_bp_diff" ~ "Δ~Pa",
                             variable == "shortwave_radiation_sum_mj_m2" ~ "MJ~m^-2",
                             variable == "precipitation_trap" ~ "m",
                             variable == "wind_speed_trap" ~ "m~s^-1",
                             variable == "delta_bp_ebu" ~ "Δ~Pa"
           )
    )
  
  return(clean_predictor_variable_names)
}